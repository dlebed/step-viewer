// Packs vendor/ sources into classic <script> bundles so step-viewer.html also works from file://
// (Chrome blocks ES-module imports, fetch() and WASM loading for local files, but not <script src>).
//   cd tests && npm install && cd .. && node build-vendor.mjs
// Inputs:  vendor/three/, vendor/three-mesh-bvh.module.js, vendor/occt/, vendor/samples/as1-oc-214.stp
// Outputs: vendor/libs.js (three + addons + BVH → window.VENDOR)
//          vendor/occt.js (occt-import-js source + base64 WASM → window.OCCT_SRC / window.OCCT_WASM_B64)
//          vendor/sample.js (sample STEP → window.SAMPLE_STEP)
import fs from 'node:fs';
import path from 'node:path';
import { createRequire } from 'node:module';
import { fileURLToPath } from 'node:url';

const root = path.dirname(fileURLToPath(import.meta.url));
const vendor = path.join(root, 'vendor');
const esbuild = createRequire(path.join(root, 'tests', 'package.json'))('esbuild');

const entry = `
export * as THREE from 'three';
export { OrbitControls } from 'three/addons/controls/OrbitControls.js';
export { CSS2DRenderer, CSS2DObject } from 'three/addons/renderers/CSS2DRenderer.js';
export { RoomEnvironment } from 'three/addons/environments/RoomEnvironment.js';
export { Line2 } from 'three/addons/lines/Line2.js';
export { LineMaterial } from 'three/addons/lines/LineMaterial.js';
export { LineGeometry } from 'three/addons/lines/LineGeometry.js';
export { MeshBVH, acceleratedRaycast, computeBoundsTree, disposeBoundsTree } from 'three-mesh-bvh';
`;
const aliases = {
  name: 'vendor-aliases',
  setup(b) {
    b.onResolve({ filter: /^three$/ }, () => ({ path: path.join(vendor, 'three/three.module.js') }));
    b.onResolve({ filter: /^three\/addons\// }, (a) => ({ path: path.join(vendor, 'three/addons', a.path.slice('three/addons/'.length)) }));
    b.onResolve({ filter: /^three-mesh-bvh$/ }, () => ({ path: path.join(vendor, 'three-mesh-bvh.module.js') }));
  },
};
await esbuild.build({
  stdin: { contents: entry, resolveDir: vendor, loader: 'js' },
  bundle: true, format: 'iife', globalName: 'VENDOR', target: 'es2020',
  outfile: path.join(vendor, 'libs.js'), plugins: [aliases], legalComments: 'inline', logLevel: 'warning',
});

const occtSrc = fs.readFileSync(path.join(vendor, 'occt/occt-import-js.js'), 'utf8');
const wasm = fs.readFileSync(path.join(vendor, 'occt/occt-import-js.wasm')).toString('base64');
fs.writeFileSync(path.join(vendor, 'occt.js'),
  `// occt-import-js 0.0.23 (LGPL-2.1), generated by build-vendor.mjs\n` +
  `window.OCCT_SRC = ${JSON.stringify(occtSrc)};\nwindow.OCCT_WASM_B64 = "${wasm}";\n`);

const sample = fs.readFileSync(path.join(vendor, 'samples/as1-oc-214.stp')).toString('base64');
fs.writeFileSync(path.join(vendor, 'sample.js'),
  `// generated by build-vendor.mjs\nwindow.SAMPLE_STEP = { name: "as1-oc-214.stp", b64: "${sample}" };\n`);

for (const f of ['libs.js', 'occt.js', 'sample.js'])
  console.log(f, (fs.statSync(path.join(vendor, f)).size / 1e6).toFixed(1), 'MB');
